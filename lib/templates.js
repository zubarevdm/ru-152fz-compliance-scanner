// Шаблоны документов по 152-ФЗ.
// Каждый шаблон возвращает структуру { filename, title, blocks } из проверенных
// формулировок, в которые подставляются данные оператора.
//
// Блоки: { type: 'h1'|'h2'|'p'|'list'|'spacer', text|items }
//
// ВАЖНО: формулировки типовые и требуют финальной вычитки. На проде каждый шаблон
// должен быть прогнан через практикующего юриста по ПД.

function operatorName(d) {
  if (d.orgType === 'ИП') {
    return `Индивидуальный предприниматель ${d.director || d.orgName || '_____'}`;
  }
  return d.orgName || '_____';
}

function dataList(d) {
  const map = {
    fio: 'фамилия, имя, отчество',
    email: 'адрес электронной почты',
    phone: 'номер телефона',
    address: 'почтовый адрес',
    cookie: 'файлы cookie, данные об активности на сайте',
    payment: 'платёжные реквизиты',
    passport: 'паспортные данные',
  };
  const picked = (d.dataCollected || []).map((k) => map[k]).filter(Boolean);
  return picked.length ? picked : ['фамилия, имя, отчество', 'номер телефона', 'адрес электронной почты'];
}

function purposeList(d) {
  const map = {
    feedback: 'обработка обращений и обратная связь с пользователями',
    contract: 'заключение и исполнение договоров',
    delivery: 'доставка товаров и оказание услуг',
    newsletter: 'информационные и рекламные рассылки (при наличии согласия)',
    analytics: 'улучшение работы сайта и веб-аналитика',
  };
  const picked = (d.purposes || []).map((k) => map[k]).filter(Boolean);
  return picked.length ? picked : ['обработка обращений и обратная связь с пользователями'];
}

